"""Add one reviewed custom-world graveyard without changing map geometry.

WorldSafeLocs.dbc has 22 fields in 3.3.5a (DBCfmt.h/DBCStructure.h).
Both server and client must receive the same generated bytes. The separate
one-file MPQ does not rebuild or replace the authored terrain/faction patches.
Binary generation writes only explicitly selected server/staging outputs.
The explicit offline bootstrap installs one private-world graveyard-zone link;
no command installs a patch into a client directory automatically.

The zone link supports the normal ghost/corpse-run recovery path. It does not
create a Spirit Healer or claim a physical death/recovery test has passed.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import json
import math
import os
from pathlib import Path
import re
import struct
import tempfile

try:
    from . import settlement_population
    from .build_map_patch import build_archive, dbc
except ImportError:
    import settlement_population
    from build_map_patch import build_archive, dbc

BOUNDS = settlement_population.BOUNDS
MANIFEST = Path(__file__).resolve().parents[2] / "data/realm_lab/aiworldlab/graveyard.json"
ARCHIVE_MEMBER = r"DBFilesClient\WorldSafeLocs.dbc"
FIELD_COUNT = 22
RECORD_SIZE = FIELD_COUNT * 4


@dataclass(frozen=True)
class Graveyard:
    safe_location_id: int
    map_id: int
    zone_id: int
    team: int
    name: str
    comment: str
    x: float
    y: float
    z: float

    @classmethod
    def load(cls, path: Path = MANIFEST) -> "Graveyard":
        value = json.loads(path.read_text(encoding="utf-8"))
        try:
            if (value["schema_version"], value["profile"], value["realm_id"],
                    value["safe_location_id"], value["map_id"], value["zone_id"], value["team"]) != (
                    1, "settlement-v8", 2, 9000, 725, 4988, 0):
                raise ValueError("Unexpected custom-world graveyard identity")
            position, source = value["position"], value["source"]
            coords = [position[field] for field in ("x", "y", "z", "ground_z")]
            if (any(type(v) not in (int, float) or not math.isfinite(v) for v in coords) or
                    not BOUNDS["min_x"] < coords[0] < BOUNDS["max_x"] or
                    not BOUNDS["min_y"] < coords[1] < BOUNDS["max_y"] or
                    abs(coords[2] - coords[3] - 2.0) > 0.00001):
                raise ValueError("Invalid graveyard position above reviewed ground")
            evidence = source["evidence"]
            if (source["revision"] != "preview-v8" or
                    any(not isinstance(source[field], str) or not re.fullmatch(r"[0-9a-f]{64}", source[field])
                        for field in ("proof_sha256", "geometry_verification_sha256")) or
                    evidence["dry"] is not True or evidence["outside_native_and_source_terrain_holes"] is not True or
                    evidence["nav_ground_projection"]["flags"] != 1 or
                    not 0 <= evidence["slope_degrees"] <= 15 or
                    evidence["outside_collision_bounds_margin"] < 2):
                raise ValueError("Graveyard requires reviewed dry ground/navmesh evidence")
            for field in ("name", "comment"):
                if (not isinstance(value[field], str) or not 0 < len(value[field]) <= 128 or
                        any(ord(c) < 32 or ord(c) > 126 for c in value[field])):
                    raise ValueError("Graveyard labels must be short printable ASCII")
            return cls(value["safe_location_id"], value["map_id"], value["zone_id"], value["team"],
                       value["name"], value["comment"], *coords[:3])
        except (KeyError, TypeError) as exc:
            raise ValueError("Incomplete custom-world graveyard manifest") from exc


def verify_point_proof(proof: bytes, manifest: Path = MANIFEST) -> None:
    """Bind private native evidence to the published point before packaging."""
    Graveyard.load(manifest)
    document = json.loads(manifest.read_text(encoding="utf-8"))
    if hashlib.sha256(proof).hexdigest() != document["source"]["proof_sha256"]:
        raise ValueError("Native graveyard point proof hash mismatch")
    source = json.loads(proof)
    if (source.get("source_revision") != document["source"]["revision"] or source.get("ok") is not True or
            source.get("status") != "pass" or source.get("bounds") != BOUNDS or
            source.get("verification_sha256") != document["source"]["geometry_verification_sha256"] or
            source.get("evidence") != document["source"]["evidence"] or
            source.get("player_entry") != {"map": 725, **document["position"]}):
        raise ValueError("Native graveyard proof does not match the published location/evidence")


def _table(data: bytes) -> tuple[list[tuple[int, ...]], bytes]:
    rows, strings = dbc(data, FIELD_COUNT, "WorldSafeLocs.dbc")
    if not rows:
        raise ValueError("WorldSafeLocs.dbc must contain its existing locations")
    if any(offset >= len(strings) for row in rows for offset in row[5:21]):
        raise ValueError("Invalid existing WorldSafeLocs localized name offset")
    return rows, strings


def verify_world_safe_locs(data: bytes, graveyard: Graveyard | None = None) -> None:
    graveyard = graveyard or Graveyard.load()
    rows, strings = _table(data)
    selected = [row for row in rows if row[0] == graveyard.safe_location_id]
    if len(selected) != 1:
        raise ValueError("Missing custom WorldSafeLocs graveyard")
    row = selected[0]
    if (struct.pack("<5I", *row[:5]) != struct.pack("<IIfff", graveyard.safe_location_id,
            graveyard.map_id, graveyard.x, graveyard.y, graveyard.z) or row[21] != 0 or
            any(strings[offset:].split(b"\0", 1)[0] != graveyard.name.encode("ascii") for offset in row[5:21])):
        raise ValueError("Reserved WorldSafeLocs graveyard ID conflicts with the reviewed location")


def patch_world_safe_locs(data: bytes, graveyard: Graveyard | None = None) -> bytes:
    """Append the reviewed location; preserve every existing row/string byte.

    Matching output is accepted byte-for-byte on repeated runs. A preexisting
    conflicting ID or an input with higher IDs refuses the append rather than
    selecting a different ID independently on server and client.
    """
    graveyard = graveyard or Graveyard.load()
    rows, strings = _table(data)
    if any(row[0] == graveyard.safe_location_id for row in rows):
        verify_world_safe_locs(data, graveyard)
        return data
    if max(row[0] for row in rows) >= graveyard.safe_location_id:
        raise ValueError("Reserved graveyard ID must be above all existing WorldSafeLocs IDs")
    name = graveyard.name.encode("ascii") + b"\0"
    record = (struct.pack("<IIfff", graveyard.safe_location_id, graveyard.map_id,
                          graveyard.x, graveyard.y, graveyard.z) +
              struct.pack("<17I", *([len(strings)] * 16), 0))
    header = struct.pack("<4s4I", b"WDBC", len(rows) + 1, FIELD_COUNT, RECORD_SIZE, len(strings) + len(name))
    result = header + data[20:20 + len(rows) * RECORD_SIZE] + record + strings + name
    verify_world_safe_locs(result, graveyard)
    return result


def build_client_patch(data: bytes, graveyard: Graveyard | None = None) -> tuple[bytes, dict]:
    """Return a deterministic one-DBC MPQ and a receipt without writing files."""
    graveyard = graveyard or Graveyard.load()
    patched = patch_world_safe_locs(data, graveyard)
    archive = build_archive({ARCHIVE_MEMBER: patched}, (("WorldSafeLocs.dbc", ARCHIVE_MEMBER),))
    return archive, {"safe_location_id": graveyard.safe_location_id, "map_id": graveyard.map_id,
                     "zone_id": graveyard.zone_id, "dbc_bytes": len(patched),
                     "dbc_sha256": hashlib.sha256(patched).hexdigest(), "patch_bytes": len(archive),
                     "patch_sha256": hashlib.sha256(archive).hexdigest(), "archive_member": ARCHIVE_MEMBER}


def verify_root_zone(area_dbc: bytes, graveyard: Graveyard | None = None) -> None:
    graveyard = graveyard or Graveyard.load()
    rows, _ = dbc(area_dbc, 36, "AreaTable.dbc")
    if not any(row[:3] == (graveyard.zone_id, graveyard.map_id, 0) for row in rows):
        raise ValueError("Graveyard zone must be the custom map's installed root zone")


def snapshot_sql(graveyard: Graveyard | None = None) -> str:
    graveyard = graveyard or Graveyard.load()
    return ("SELECT JSON_OBJECT('id',ID,'zone',GhostZone,'team',Faction,'comment',Comment) "
            f"FROM world.graveyard_zone WHERE ID={graveyard.safe_location_id} OR GhostZone={graveyard.zone_id};")


def validate_links(rows: list[dict], graveyard: Graveyard | None = None, *, allow_absent: bool = False) -> None:
    graveyard = graveyard or Graveyard.load()
    expected = {"id": graveyard.safe_location_id, "zone": graveyard.zone_id,
                "team": graveyard.team, "comment": graveyard.comment}
    if not (rows == [expected] or (allow_absent and rows == [])):
        raise ValueError("Graveyard-zone link conflicts with reviewed custom-world routing")


def bootstrap_sql(graveyard: Graveyard | None = None) -> str:
    """Guarded INSERT only; callers must verify DBC and link read-back."""
    graveyard = graveyard or Graveyard.load()
    comment = "'" + graveyard.comment.replace("'", "''") + "'"
    return f"""START TRANSACTION;
INSERT INTO world.graveyard_zone (ID,GhostZone,Faction,Comment)
SELECT {graveyard.safe_location_id},{graveyard.zone_id},{graveyard.team},{comment}
WHERE NOT EXISTS (SELECT 1 FROM world.graveyard_zone
 WHERE ID={graveyard.safe_location_id} OR GhostZone={graveyard.zone_id});
COMMIT;
"""


def verify_data(data: Path, graveyard: Graveyard | None = None) -> Graveyard:
    """Require the installed custom root zone and the exact generated safe loc."""
    graveyard = graveyard or Graveyard.load()
    verify_root_zone((data / "dbc/AreaTable.dbc").read_bytes(), graveyard)
    verify_world_safe_locs((data / "dbc/WorldSafeLocs.dbc").read_bytes(), graveyard)
    return graveyard


def _check_output(path: Path, expected: bytes, previous: bytes | None = None) -> bool:
    if not path.exists():
        return True
    current = path.read_bytes()
    if current == expected:
        return False
    if previous is None or current != previous:
        raise ValueError(f"Existing graveyard output differs from its reviewed input/output: {path}")
    return True


def _write_output(path: Path, expected: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Replacement is atomic: the reader never sees a truncated DBC or MPQ.
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(expected)
        # DBC/MPQ data are public assets. The build may run as root while the
        # worldserver runs as the configured dev UID in another container.
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def build_server(data: Path, base: Path, client_patch: Path, graveyard: Graveyard | None = None) -> dict:
    """Generate server DBC and a staged client MPQ, retaining the vanilla base.

    A server output identical to the supplied base can be upgraded once.
    Matching generated output is a no-op; other existing bytes fail before
    either destination is written. The MPQ destination is a staging location,
    never inferred from a WoW client directory.
    """
    graveyard = graveyard or Graveyard.load()
    server_output = (data / "dbc/WorldSafeLocs.dbc").resolve()
    base = base.resolve()
    client_patch = client_patch.resolve()
    if base == server_output or client_patch.suffix.lower() != ".mpq":
        raise ValueError("Keep the immutable graveyard base separate and select a staged MPQ output")
    verify_root_zone((data / "dbc/AreaTable.dbc").read_bytes(), graveyard)
    base_bytes = base.read_bytes()
    patched = patch_world_safe_locs(base_bytes, graveyard)
    archive, receipt = build_client_patch(base_bytes, graveyard)
    write_server = _check_output(server_output, patched, base_bytes)
    write_patch = _check_output(client_patch, archive)
    if write_server:
        _write_output(server_output, patched)
    if write_patch:
        _write_output(client_patch, archive)
    verify_data(data, graveyard)
    if client_patch.read_bytes() != archive:
        raise ValueError("Staged graveyard client patch read-back differs")
    return {**receipt, "server_output": str(server_output), "client_patch_output": str(client_patch),
            "server_written": write_server, "client_patch_written": write_patch,
            "base_sha256": hashlib.sha256(base_bytes).hexdigest()}


def bootstrap(data: Path, settings=None, graveyard: Graveyard | None = None) -> dict:
    """Install the reviewed private-world zone link only with the world offline."""
    # Lazy import keeps binary-data generation independent of database setup.
    try:
        from . import manage
    except ImportError:
        import manage
    settings = settings or manage.Settings.load(os.environ)
    if settings.ai_profile not in ("disabled", settlement_population.PROFILE, "wildlife-v8", "supply-v8", "consumers-v8", "raids-v8", "fields-v8", "defias-v8"):
        raise ValueError("Graveyard bootstrap requires the native settlement profile and a stopped world")
    settlement_population.ensure_world_offline()
    graveyard = verify_data(data, graveyard)

    def read_links() -> list[dict]:
        return [json.loads(line) for line in manage.lab_mysql(settings, snapshot_sql(graveyard)).splitlines()
                if line.strip()]

    validate_links(read_links(), graveyard, allow_absent=True)
    settlement_population.ensure_world_offline()
    manage.lab_mysql(settings, bootstrap_sql(graveyard))
    settlement_population.ensure_world_offline()
    validate_links(read_links(), graveyard)
    return {"status": "verified", "safe_location_id": graveyard.safe_location_id,
            "map_id": graveyard.map_id, "zone_id": graveyard.zone_id, "team": graveyard.team,
            "spirit_healer_spawned": False, "physical_recovery_verified": False}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    build = commands.add_parser("build-server", help="Generate matching server DBC and staged client MPQ")
    build.add_argument("data", type=Path)
    build.add_argument("--base", type=Path, required=True)
    build.add_argument("--client-patch", type=Path, required=True)
    initialize = commands.add_parser("bootstrap", help="Install the private custom-zone link offline")
    initialize.add_argument("data", type=Path)
    args = parser.parse_args()
    try:
        result = (build_server(args.data, args.base, args.client_patch) if args.command == "build-server"
                  else bootstrap(args.data))
    except (OSError, ValueError) as exc:
        parser.exit(2, f"Graveyard preparation refused: {exc}\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
